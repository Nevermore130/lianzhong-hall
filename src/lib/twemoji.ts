import twemoji from "twemoji";

/**
 * Parse text and replace emoji with Twemoji images.
 * XSS-safe: escapes HTML in text before injecting Twemoji img tags.
 *
 * @param text - User text that may contain emoji
 * @returns HTML string with Twemoji img tags
 */
export function parseTwemoji(text: string): string {
  // Escape HTML to prevent XSS
  const escaped = text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

  // Parse emoji and replace with Twemoji images
  return twemoji.parse(escaped, {
    folder: "svg",
    ext: ".svg",
    base: "https://cdn.jsdelivr.net/gh/twitter/twemoji@latest/assets/",
  });
}

